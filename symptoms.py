def _norm(s: str) -> str:
    return re.sub(r"\s+", " ", s.lower().replace("ё", "е")).strip()


def check_danger(text: str) -> str | None:
    """'crisis' / 'emergency' / None."""
    t = _norm(text)
    if any(_norm(k) in t for k in CRISIS):
        return "crisis"
    if any(_norm(k) in t for k in EMERGENCY):
        return "emergency"
    return None


def match_symptoms(text: str) -> list[str]:
    t = _norm(text)
    return [key for key, s in SYMPTOMS.items() if any(_norm(k) in t for k in s["keys"])]


def mentions_child(text: str) -> bool:
    t = _norm(text)
    return any(w in t for w in ("ребен", "ребён", "детск", "дочь", "дочк", "сын", "малыш", "младен"))


def symptom_text(key: str, child: bool = False) -> str:
    s = SYMPTOMS[key]
    lines = [f"<b>{s['title']}</b>\n", "Обычно помогают (безрецептурные средства):"]
    lines += [f"• {h}" for h in s["help"]]
    lines.append("\nДозировку смотрите <b>в инструкции</b> к препарату.")
    lines.append("\n🩺 <b>Обратитесь к врачу, если:</b>")
    lines += [f"• {d}" for d in s["doctor"]]
    if child:
        lines.append("\n" + CHILD_NOTE)
    lines.append("\n" + DISCLAIMER)
    return "\n".join(lines)
