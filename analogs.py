# ------------------------------------------------------------------ разбор таблицы

ENTRIES: list[dict] = []          # [{"inn", "group", "brands"}]
for _line in DATA.strip().splitlines():
    if not _line.strip() or _line.strip().startswith("#"):
        continue
    _inn, _grp, _brands = (p.strip() for p in _line.split("|"))
    assert _grp in GROUPS, f"неизвестная группа {_grp} в строке: {_line}"
    ENTRIES.append({"inn": _inn, "group": _grp,
                    "brands": [b.strip() for b in _brands.split(",") if b.strip()]})

# ------------------------------------------------------------------ нормализация

_LAYOUT = dict(zip("qwertyuiop[]asdfghjkl;'zxcvbnm,.`",
                   "йцукенгшщзхъфывапролджэячсмитьбюё"))
_TRANSLIT = [("shch", "щ"), ("sch", "щ"), ("yo", "ё"), ("zh", "ж"), ("kh", "х"), ("ts", "ц"),
             ("ch", "ч"), ("sh", "ш"), ("yu", "ю"), ("ya", "я"), ("ph", "ф"), ("x", "кс"),
             ("a", "а"), ("b", "б"), ("c", "ц"), ("d", "д"), ("e", "е"), ("f", "ф"), ("g", "г"),
             ("h", "х"), ("i", "и"), ("j", "й"), ("k", "к"), ("l", "л"), ("m", "м"), ("n", "н"),
             ("o", "о"), ("p", "п"), ("q", "к"), ("r", "р"), ("s", "с"), ("t", "т"), ("u", "у"),
             ("v", "в"), ("w", "в"), ("y", "ы"), ("z", "з")]
# слова, которые не относятся к названию: формы выпуска, дозировки и т.п.
_NOISE = {"таблетки", "таблетка", "таб", "табл", "капсулы", "капсула", "капс", "сироп", "спрей",
          "мазь", "гель", "крем", "капли", "раствор", "порошок", "суспензия", "свечи", "мг", "мл",
          "г", "шт", "уколы", "ампулы", "аналог", "аналоги", "аналогичное", "дешевле", "дешевый",
          "дешевые", "купить", "цена", "для", "детей", "детский", "взрослых", "от", "n", "№"}


def _clean(s: str) -> str:
    s = s.lower().replace("ё", "е")
    s = re.sub(r"[^a-zа-я0-9 ]+", " ", s)
    words = [w for w in s.split() if w not in _NOISE and not w.isdigit()
             and not re.fullmatch(r"\d+(мг|мл|г|mg|ml)?", w)]
    return " ".join(words)


def _variants(query: str) -> list[tuple[str, str]]:
    """Варианты прочтения запроса: как есть, в русской раскладке, транслитом."""
    raw = query.lower().replace("ё", "е")
    out = [("", _clean(raw))]
    if re.search(r"[a-z]", raw):
        out.append(("layout", _clean("".join(_LAYOUT.get(ch, ch) for ch in raw))))
        t = raw
        for lat, cyr in _TRANSLIT:
            t = t.replace(lat, cyr)
        out.append(("translit", _clean(t)))
    return [(k, v) for k, v in out if v]

# ------------------------------------------------------------------ индекс для поиска

NAMES: list[str] = []             # все названия (для кнопок «вы имели в виду»)
_INDEX: dict[str, int] = {}       # нормализованное название -> номер записи в ENTRIES
_NAME_OF: dict[str, str] = {}     # нормализованное название -> красивое название
_FIRST: dict[str, int] = {}       # первое слово -> номер записи (если однозначно)

for _i, _e in enumerate(ENTRIES):
    for _name in [_e["inn"]] + _e["brands"]:
        _k = _clean(_name)
        if not _k or _k in _INDEX:
            continue
        _INDEX[_k] = _i
        _NAME_OF[_k] = _name
        NAMES.append(_name)
        _fw = _k.split()[0]
        if len(_fw) >= 4:
            _FIRST.setdefault(_fw, _i)

_KEYS = list(_INDEX)
_FIRST_KEYS = list(_FIRST)


def _best(q: str) -> tuple[float, str | None]:
    if q in _INDEX:
        return 1.0, q
    m = difflib.get_close_matches(q, _KEYS, n=1, cutoff=0.0)
    return (difflib.SequenceMatcher(None, q, m[0]).ratio(), m[0]) if m else (0.0, None)


def search(query: str) -> dict:
    """
    Ищет лекарство с учётом опечаток.
    Возвращает:
      {"status": "found", "entry": {...}, "matched": "Нурофен", "corrected": bool}
      {"status": "suggest", "options": ["Нурофен", "Нурофен Экспресс", ...]}
      {"status": "none"}
    """
    best_score, best_key, best_kind = 0.0, None, ""
    for kind, q in _variants(query):
        # 1) точное совпадение
        if q in _INDEX:
            return {"status": "found", "entry": ENTRIES[_INDEX[q]], "matched": _NAME_OF[q],
                    "corrected": kind != "", "score": 1.0}
        # 2) первое слово ("нурофен экспресс форте" -> нурофен)
        fw = q.split()[0]
        if fw in _FIRST:
            e = ENTRIES[_FIRST[fw]]
            return {"status": "found", "entry": e, "matched": _NAME_OF.get(_clean(fw), fw.capitalize()),
                    "corrected": kind != "", "score": 1.0}
        # 3) нечёткий поиск по полному названию и по первому слову
        for cand in (q, fw):
            score, key = _best(cand)
            if cand == fw:
                m = difflib.get_close_matches(fw, _FIRST_KEYS, n=1, cutoff=0.0)
                if m:
                    s2 = difflib.SequenceMatcher(None, fw, m[0]).ratio()
                    if s2 > score:
                        score, key = s2, next(k for k in _KEYS if k.split()[0] == m[0])
            if score > best_score:
                best_score, best_key, best_kind = score, key, kind

    # короткие слова легко спутать («привет» ~ «Париет»), для них порог строже
    need = 0.86 if len(_clean(query)) <= 6 else 0.8
    if best_key and best_score >= need:
        return {"status": "found", "entry": ENTRIES[_INDEX[best_key]],
                "matched": _NAME_OF[best_key], "corrected": True, "score": best_score}

    # подсказки «возможно, вы имели в виду»
    opts: list[str] = []
    for _, q in _variants(query):
        for cand in (q, q.split()[0]):
            for m in difflib.get_close_matches(cand, _KEYS, n=4, cutoff=0.72):
                name = _NAME_OF[m]
                if name not in opts:
                    opts.append(name)
    if opts:
        return {"status": "suggest", "options": opts[:4]}
    return {"status": "none"}


def same_group(entry: dict, limit: int = 5) -> list[dict]:
    """Другие действующие вещества той же группы (похожее действие, но это не прямые аналоги)."""
    return [e for e in ENTRIES if e["group"] == entry["group"] and e is not entry][:limit]


def group_info(entry: dict) -> tuple[str, bool]:
    return GROUPS[entry["group"]]


def find_analogs(query: str) -> tuple[str, list[str]] | None:
    """Совместимость со старым кодом: (действующее вещество, препараты) или None."""
    r = search(query)
    if r["status"] != "found":
        return None
    return r["entry"]["inn"], r["entry"]["brands"]
